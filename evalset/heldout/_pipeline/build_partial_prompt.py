# -*- coding: utf-8 -*-
r"""拼「部分可答」批次的出题包 prompt（只给底本，别的什么都不给）。

为什么要单独一批（2026-10-16）
================================
跨模型调研（`D:\dsh-work\AI实习简历-筛选方视角-调研.md`）挖到一份**真实实习 take-home**：
"policy document RAG + 强制引用 + 答不了安全兜底 + 7 题评测集分三类
（answerable / **partially answerable** / unanswerable）"。
⇒ 我们的两套题只有 **answer / refuse 二分类**，缺"部分可答"这一档。

★ 为什么这不算"加功能"，算"补测试"：
  `service.py:987` 的生成 prompt 早就写着「只根据下面的资料回答，资料里没有的就明确说不知道」
  —— 行为契约在，但**没有任何一道题在测它**（零覆盖）。
  所以本批**不改产品行为**，只把"它到底做没做到"量出来。

★ "盲"怎么保证（与 `build_heldout_prompt.py` 同一套规矩）
  1. 出题人拿到的是全新会话，只看到本 prompt 里的文字；
  2. 不给工具、不给仓库路径、工作目录是空目录；
  3. prompt 里只有：出题说明书 + 校规原文，没有现有题、没有检索信息。
  ⚠️ 它和项目作者同模型（deepseek-flash）⇒"盲"= 没看过数据，**不等于独立第三方**。

★ 这批与 holdout 的差别只在一处：**要它挑"底本只答一半"的问题**。
  注意出题人看到的是**原文底本**，不是实际入库的 chunk —— 所以它写的 gold
  必须由 `apply_partial.py` 拿真库逐条校验（和原批次一样）。
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO = Path(r"D:\_review_rag-cs")
HELDOUT = REPO / "evalset" / "heldout"
OUT = Path(r"D:\dsh-work\_task_partial.md")

src = (HELDOUT / "source_policy.md").read_text(encoding="utf-8")

head = """你是一位**独立的出题人**。你的任务：为下面这份校规原文出一套**特定类型**的评测题。

# 硬约束（违反任何一条，这套题就废了）

1. **你只能看这份 prompt 里的文字。** 你没有工具、也不能读任何文件。
   不要试图访问仓库、不要问我"能不能看看别的"。你手上这些就是全部材料。
2. **不要参考任何现成的问答系统**：不要想"RAG 会怎么答"，只想"一个真实学生会怎么问"。
3. 出题的措辞要**像学生说的**，不要抄条款标题：
   - ✅「要请一个礼拜的假得谁批啊」
   - ❌「请假一周的审批权限是什么」——这是条款标题，不是学生的问法
   **刻意制造用词差异**：条款写"请假"，你写"请个假"；条款写"开除学籍"，你写"直接开除"。

# 这批题的特殊要求：全部是「**部分可答**」

这道题的**前半部分**在底本里查得到，**后半部分（某个关键细节）底本里压根没有**。
也就是说：一个只会照底本回答的助手，应该
**把查得到的那半答出来，同时明确说出哪一半它答不了** —— 既不该整题拒答，也不该硬编。

**必须真的"半有半无"，不能是"全有"或"全无"：**
- ❌ 全有：「请病假要什么材料」——底本写全了 ⇒ 那是 answer 题，不是这批要的。
- ❌ 全无：「食堂几点开门」——底本一个字没提 ⇒ 那是 refuse 题。
- ✅ 半有半无：「**病假要交什么材料，交上去之后多久能批下来**」
    前半（材料）底本有；后半（时限）底本没写 ⇒ 这才是 partial。

**出题窍门（推荐用，但不强制）：把两个问题焊成一句。**
一个底本答得上、一个底本答不上，用"以及 / 还有 / 顺便问下"连起来。
这类题最能暴露系统的真实行为。

**三道以上要跨两份不同文件**（前半在一份文件、要补的那半在另一份或压根没有）。

# 每道题必须写清三件事

| 字段 | 写什么 | 反例（不要这样写） |
|---|---|---|
| `gold` | `[文件名, 条款名]` —— **只填"答得上那半"对应的条款**，逐字照底本抄 | 不要填两条，除非两半都有对应条款（那样就不是 partial 了） |
| `answerable_part` | 底本**能**回答的那半，一句话 | "请假相关的规定" —— 太虚，要说具体到哪个值 |
| `missing_part` | 底本**答不了**的那半，**具体到"缺哪个值"** | "没有相关规定" —— 必须说清缺的是"时限"还是"金额"还是"谁签字" |

⚠️ `missing_part` 是这批题唯一的价值所在。写不出具体的缺口，这道题就删掉别交。

# 出什么、出几道

- **partial 题 8 道**。
- 覆盖面尽量散开：请假/处分/资助/宿舍/评奖/实习/学籍 等不同主题各来一点，
  别 8 道全问请假。
- `note` 里可以写你认为的难点（比如"我怀疑系统会硬编时限"）。

# 输出格式（**只输出 JSON，不要任何解释文字、不要 markdown 代码围栏**）

{
  "_说明": ["谁出的、什么时候、依据什么"],
  "questions": [
    {"id": "p1", "type": "partial", "question": "...",
     "gold": ["文件名.md", "章-条"],
     "answerable_part": "底本答得上的那半",
     "missing_part": "底本没有的那个值（具体到是什么值）",
     "note": ""}
  ]
}

`id` 用 p1、p2、p3……按顺序编。条款名必须与底本里 `###` 后面的字**逐字一致**。

================================================================================
下面是校规原文底本（你唯一的材料）
================================================================================

"""

OUT.write_text(head + src, encoding="utf-8")
print(f"✓ 已写出题包：{OUT}")
