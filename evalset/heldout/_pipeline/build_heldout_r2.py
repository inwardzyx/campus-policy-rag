# -*- coding: utf-8 -*-
"""拼第二轮 held-out 出题包：继续盲出题，把独立集做大。

为什么要第二轮：held-out 首轮只有 19 道应答题，暴露出"仅向量 17/19 vs 融合 14/19"
这个 3 道之差，但 **n=19 时 McNemar p=0.25，不足以改架构**。
⇒ 不把独立集做大，第一项（修融合）就永远只能用方向性证据拍板。

这一轮的改进（相对第一轮）：
  1. **列出已被覆盖的条款名**，要求只从没覆盖的条款出题
     —— 注意只给【条款名】，不给任何题目文字，所以出题人对"别人问过什么"仍然是盲的；
  2. **拒答题按 6 类出**（README §8.6 的待办就是这个），每类 ≥5 道。
     随机出的拒答题多半是送分题（跟语料零字面交集），6 类出题才能压出真实边界：
       ① 域外（跟学校制度无关）          ② 同域未覆盖（学校有这类制度，但没入库）
       ③ 提到主题未给取值（沾边但没有那个值）④ 版本/时间不匹配（问已废止或未来生效的）
       ⑤ 错误前提（问题本身建立在错误假设上）⑥ 多跳（要跨条款/跨文件才能答）
  3. 目标规模：answer 20 道 + refuse 30 道（refuse 是这轮的重点）。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO = Path(r"D:\_review_rag-cs")
HELDOUT = REPO / "evalset" / "heldout"
OUT = Path(r"D:\dsh-work\_task_heldout_r2.md")

# ---- 已被覆盖的条款名（主评测集 + 第一轮 held-out）——只给名字，不给题面 ----
covered: set[tuple[str, str]] = set()
for p in (REPO / "evalset" / "questions.json", HELDOUT / "questions.json"):
    d = json.loads(p.read_text(encoding="utf-8"))
    qs = d.get("questions") if isinstance(d, dict) else d
    for q in qs:
        if q.get("gold"):
            covered.add((q["gold"][0], q["gold"][1]))

covered_lines = "\n".join(f"- {doc}｜{clause}" for doc, clause in sorted(covered))
src = (HELDOUT / "source_policy.md").read_text(encoding="utf-8")

head = f"""你是一位**独立的出题人**。这次是**第二轮**：上一轮已经出过 25 道题，现在要把这套题做大。

# 硬约束（违反任何一条，这套题就废了）

1. **你只能看这份 prompt 里的文字。** 你没有工具、不能读任何文件。你手上这些就是全部材料。
2. 不要想"某个系统会怎么答"，只想"一个真实学生会怎么问"。
3. 题面要**像学生说的**，不要抄条款标题。刻意制造用词差异：
   条款写"请假"，你写"请个假"；条款写"开除学籍"，你写"直接开除"；条款写"擅自"，你写"没打招呼就"。
4. **下面列出的条款已经被问过了，请不要再给它们出题**（题面你不需要知道，避开条款即可）：

{covered_lines}

# 这一轮出什么（重点变了：**拒答题是主角**）

## A. answer 题 20 道
从**没有被上面列出的**条款里出。`gold` 填 `[文件名, 条款名]`，逐字抄底本里的名字。
其中至少 6 道要是 **multi-hop**（跨两份文件或跨条款才能答完整），在 note 里写清要引哪几条。

## B. refuse 题 30 道 ★ 这一轮的重点

**不要随便挑"学校没提的事"** —— 那种题跟语料零字面交集，是送分题，测不出东西。
请**按下面 6 类各出 5 道**（每道都要在 `why_forced_to_refuse` 里写明属于哪一类、以及为什么）：

| 类 | 意思 | 例子（不要照抄，你要自己找） |
|---|---|---|
| ① 域外 | 跟学校学生制度无关 | 周边哪家奶茶店好吃 |
| ② 同域未覆盖 | 学校**有**这类制度，但那份文件**没入库** | 学生公寓管理规定里写的熄灯时间 |
| ③ 提到主题未给取值 | 库里沾了这个主题，但**没有用户要的那个值** | 问"学费多少"，库里只有"减免学费的额度" |
| ④ 版本/时间不匹配 | 问的是已废止的旧规定，或还没生效的 | 按 2019 年那份已废止的考核办法算 |
| ⑤ 错误前提 | 问题本身建立在错误假设上 | "挂科两门就要退学对吧？"（制度里没这条） |
| ⑥ 多跳但库里缺一环 | 要跨条款答，而其中一条根本不存在 | 问"休学期间能申请奖学金吗"（休学和评奖各有规定，但没有交叉条款） |

③⑤⑥ 这三类最有价值 —— 它们跟语料**字面很近**，会真的把检索分数顶上去，
然后考验系统"有没有那个值"的判断力。**多出这三类。**

# 输出格式（**只输出 JSON，不要解释、不要 markdown 代码围栏**）

{{
  "_说明": ["第二轮；谁出的、依据什么"],
  "questions": [
    {{"id": "r1", "type": "answer", "question": "...", "gold": ["文件名.md", "章-条"], "note": ""}},
    {{"id": "r2", "type": "refuse", "question": "...", "gold": null,
      "why_forced_to_refuse": "【类③】库里有……但问的是……，没有那个值"}}
  ]
}}

`id` 用 r1、r2、r3……按顺序编。条款名必须与底本里 `###` 后面的字**逐字一致**。

================================================================================
下面是出题人说明书（更细的规则与反例）
================================================================================

"""

tail = """

================================================================================
下面是校规原文底本（你唯一的材料）
================================================================================

"""

OUT.write_text(head + (HELDOUT / "README.md").read_text(encoding="utf-8") + tail + src,
               encoding="utf-8")
print(f"已写出 {OUT}（{OUT.stat().st_size:,} 字节）")
print(f"  已覆盖条款 {len(covered)} 条（只给了名字，没给题面）")
print(f"  目标：answer 20 + refuse 30（拒答按 6 类各 5 道）")
