# -*- coding: utf-8 -*-
"""拼 held-out 出题包的 prompt（只给底本，别的什么都不给）。

为什么要脚本拼、而不是我手抄进上下文：
  底本 100KB+，抄一遍等于把它整个塞进我的上下文（而且之后每轮都重发）。
  脚本拼 → 我一行都不用读。

★ "盲"是怎么保证的（这是 held-out 成立的前提）：
  1. 出题人拿到的是**全新会话**（不带任何历史），只看到本 prompt 里的文字；
  2. 不给它任何工具、不加 --add-dir，工作目录设成一个**空目录** ——
     它没有任何通道去读仓库、评测集或 chunk；
  3. prompt 里只有：出题说明书 + 校规原文，**没有**现有 20 题、没有检索信息。
  ⚠️ 它和我同模型（deepseek-flash），所以"盲"是"没看过数据"，不是"不同的先验"。
     这一点必须写在报告里，别把它说成"独立第三方"。
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO = Path(r"D:\_review_rag-cs")
HELDOUT = REPO / "evalset" / "heldout"
OUT = Path(r"D:\dsh-work\_task_heldout.md")

readme = (HELDOUT / "README.md").read_text(encoding="utf-8")
src = (HELDOUT / "source_policy.md").read_text(encoding="utf-8")

head = """你是一位**独立的出题人**。你的任务：为下面这份校规原文出一套评测题。

# 硬约束（违反任何一条，这套题就废了）

1. **你只能看这份 prompt 里的文字。** 你没有工具、也不能读任何文件。
   不要试图访问仓库、不要问我"能不能看看别的"。你手上这些就是全部材料。
2. **不要参考任何现成的问答系统**：不要想"RAG 会怎么答"，只想"一个真实学生会怎么问"。
3. 下面给的是**校规原文底本**（按条款排好，标了 `[已覆盖]`/`[未覆盖]`）。
   `[未覆盖]` = 现有评测集还没问过这些条款，**优先从它们出题**。
4. 出题的措辞要**像学生说的**，不要抄条款标题（这是这套题唯一的价值所在）：
   - ✅「要请一个礼拜的假得谁批啊」
   - ❌「请假一周的审批权限是什么」——这是条款标题，不是学生的问法
   **刻意制造用词差异**：条款写"请假"，你写"请个假"；条款写"开除学籍"，你写"直接开除"。
5. 每道 refuse 题必须写清 `why_forced_to_refuse`：**库里哪一条都没提这件事**，
   而且要具体到"没有哪个值"，不能只写"没相关规定"。

# 出什么、出几道

- **answer 题 14 道**：`gold` 填 `[文件名, 条款名]` 两级，照底本里的名字逐字抄。
- **refuse 题 6 道**：`gold` 填 `null`。选那些校规**压根没提**的事
  （场馆开放时间、食堂、缴费标准、办证补办、校历之类）。
  ⚠️ 判断标准是**"库里有没有用户要的那个值"**，不是"像不像"：
  问"学费多少钱"，而库里只有"减免学费的额度" ⇒ 那是 refuse（有额度 ≠ 有标准）。
- **multi-hop 边界题 5 道**：必须**跨两份文件、或同一文件里跨条款**才能答完整。
  这类最有价值：当前系统只看 top-1 最高分，所以它们**很可能被误拒**——那正是要测的。
  如果某道你写不出确定的 gold，就在 note 里写"我认为是跨条款的，但该引哪条我不确定"。
  这种诚实标注比硬填一个错 gold 有用得多。

# 输出格式（**只输出 JSON，不要任何解释文字、不要 markdown 代码围栏**）

{
  "_说明": ["谁出的、什么时候、依据什么"],
  "questions": [
    {"id": "h1", "type": "answer", "question": "...", "gold": ["文件名.md", "章-条"], "note": ""},
    {"id": "h2", "type": "refuse", "question": "...", "gold": null,
     "why_forced_to_refuse": "库里的哪一条都没提……"},
    {"id": "h3", "type": "answer", "question": "...", "gold": ["文件名.md", "章-条"],
     "note": "跨条款：需要 X 条 + Y 条一起答", "multi_hop": true}
  ]
}

`id` 用 h1、h2、h3……按顺序编。条款名必须与底本里 `###` 后面的字**逐字一致**。

================================================================================
下面是出题人说明书（更细的规则与反例，和上面不冲突）
================================================================================

"""

tail = """

================================================================================
下面是校规原文底本（你唯一的材料）
================================================================================

"""

OUT.write_text(head + readme + tail + src, encoding="utf-8")
print(f"已写出 {OUT}")
print(f"  说明书 {len(readme):,} 字符 + 底本 {len(src):,} 字符 = {OUT.stat().st_size:,} 字节")
print(f"  ★ 里面没有现有 20 题、没有任何检索信息、没有 chunk —— 盲的条件成立")
